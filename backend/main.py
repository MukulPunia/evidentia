def discard_excluded_upload(artifact: Artifact) -> None:
    """Remove an explicitly excluded upload from temporary storage.

    Do not delete anything outside UPLOAD_DIR; this helper only receives paths
    generated by save_uploaded_file for the current upload request.
    """
    raw_path = getattr(artifact, "local_path", None)
    if not raw_path:
        return
    try:
        saved_path = Path(raw_path).resolve()
        upload_root = Path(UPLOAD_DIR).resolve()
        if upload_root in saved_path.parents and saved_path.is_file():
            saved_path.unlink()
            try:
                saved_path.parent.rmdir()
            except OSError:
                pass
    except OSError:
        # The analysis response still identifies the exclusion; a cleanup
        # failure should not turn a scope mismatch into accepted evidence.
        pass
    artifact.local_path = None
